import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const indexingEnabled = process.env.AHAFRAME_INDEXING_ENABLED === "1";
const targetDir = resolve(process.cwd(), ".generated");
const target = resolve(targetDir, "build-mode.ts");

await mkdir(targetDir, { recursive: true });
await writeFile(
  target,
  `// Generated by scripts/write-build-mode.mjs. Do not edit.\nexport const INDEXING_ENABLED = ${indexingEnabled ? "true" : "false"} as const;\n`,
  "utf8",
);

console.log(`Wrote build mode: indexing=${indexingEnabled ? "enabled" : "blocked"}.`);
